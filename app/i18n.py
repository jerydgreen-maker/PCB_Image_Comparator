class LanguageBroker(QObject):
    languageChanged = Signal(str)

    def __init__(self) -> None:
        super().__init__()
        self._lang = str(qt_settings().value("language", LANG_EN) or LANG_EN)
        if self._lang not in (LANG_EN, LANG_RU):
            self._lang = LANG_EN
        self._log_lang = str(qt_settings().value("log_language", LOG_FOLLOW) or LOG_FOLLOW)

    @property
    def language(self) -> str:
        return self._lang

    @property
    def log_language(self) -> str:
        if self._log_lang == LOG_FOLLOW:
            return self._lang
        return self._log_lang

    def set_language(self, lang: str) -> None:
        if lang not in (LANG_EN, LANG_RU):
            return
        self._lang = lang
        qt_settings().setValue("language", lang)
        self.languageChanged.emit(lang)

    def set_log_language(self, mode: str) -> None:
        if mode not in (LOG_FOLLOW, LOG_EN, LOG_RU):
            return
        self._log_lang = mode
        qt_settings().setValue("log_language", mode)


_broker: LanguageBroker | None = None


def broker() -> LanguageBroker:
    global _broker
    if _broker is None:
        _broker = LanguageBroker()
    return _broker


def language() -> str:
    return broker().language


def tr(key: str, **kwargs) -> str:
    table = _STRINGS.get(language()) or _STRINGS[LANG_EN]
    text = table.get(key) or _STRINGS[LANG_EN].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


