def tr_menu(english: str) -> str:
    if language() == LANG_RU:
        return MENU_RU.get(english, english)
    return english


def log_tr(key: str, **kwargs) -> str:
    lang = broker().log_language
    table = _STRINGS.get(lang) or _STRINGS[LANG_EN]
    text = table.get(key) or _STRINGS[LANG_EN].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
